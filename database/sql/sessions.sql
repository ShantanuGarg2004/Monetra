-- One row per sign-in. Logout revokes that row only.
-- Applied on startup from database/models.py. Safe to run again.

CREATE TABLE IF NOT EXISTS sessions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id           BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    secret_hash          TEXT NOT NULL,
    previous_secret_hash TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at           TIMESTAMPTZ NOT NULL,
    revoked_at           TIMESTAMPTZ,
    last_seen_at         TIMESTAMPTZ,
    user_agent           TEXT
);

CREATE INDEX IF NOT EXISTS idx_sessions_account
    ON sessions (account_id);

CREATE INDEX IF NOT EXISTS idx_sessions_secret_hash
    ON sessions (secret_hash);

CREATE INDEX IF NOT EXISTS idx_sessions_previous_secret_hash
    ON sessions (previous_secret_hash)
    WHERE previous_secret_hash IS NOT NULL;
