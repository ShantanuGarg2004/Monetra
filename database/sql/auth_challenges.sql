-- Email verification. The backfill runs only when email_verified_at is added,
-- so a later startup does not mark new signups verified.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'accounts'
      AND column_name = 'email_verified_at'
  ) THEN
    ALTER TABLE accounts ADD COLUMN email_verified_at TIMESTAMPTZ;
    UPDATE accounts
    SET email_verified_at = created_at
    WHERE email_verified_at IS NULL;
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS auth_challenges (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    purpose       TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password', 'change_email')),
    secret_hash   TEXT NOT NULL,
    target_email  TEXT,
    expires_at    TIMESTAMPTZ NOT NULL,
    consumed_at   TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_auth_challenges_open
    ON auth_challenges (account_id, purpose)
    WHERE consumed_at IS NULL;

-- Existing databases already have the verify_email-only check. Replace it.
DO $$
DECLARE
  constraint_name text;
BEGIN
  SELECT c.conname INTO constraint_name
  FROM pg_constraint c
  JOIN pg_class t ON c.conrelid = t.oid
  JOIN pg_namespace n ON t.relnamespace = n.oid
  WHERE n.nspname = current_schema()
    AND t.relname = 'auth_challenges'
    AND c.contype = 'c'
    AND pg_get_constraintdef(c.oid) ILIKE '%purpose%';
  IF constraint_name IS NOT NULL THEN
    EXECUTE format('ALTER TABLE auth_challenges DROP CONSTRAINT %I', constraint_name);
  END IF;
  ALTER TABLE auth_challenges
    ADD CONSTRAINT auth_challenges_purpose_check
    CHECK (purpose IN ('verify_email', 'reset_password', 'change_email'));
END $$;
