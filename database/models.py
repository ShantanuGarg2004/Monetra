def _allow_chat_jobs(conn):
    """Existing databases were created when jobs.kind allowed only reports.

    A check that already allows report and chat is left in place. A second
    startup must not drop and recreate it.
    """
    rows = conn.execute(
        """
        SELECT conname AS name, pg_get_constraintdef(oid) AS definition
        FROM pg_constraint
        WHERE conrelid = 'jobs'::regclass
          AND contype = 'c'
          AND pg_get_constraintdef(oid) ILIKE '%kind%'
        """
    ).fetchall()
    has_current = False
    for row in rows:
        definition = (row["definition"] or "").lower()
        if "report" in definition and "chat" in definition:
            has_current = True
            continue
        name = row["name"]
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            continue
        conn.execute(f"ALTER TABLE jobs DROP CONSTRAINT {name}")
    if not has_current:
        conn.execute(
            "ALTER TABLE jobs ADD CONSTRAINT jobs_kind_check CHECK (kind IN ('report', 'chat'))"
        )


def create_tables():
    """
    Create the application tables if they do not exist.
    Safe to call on every startup. A SQLite file is opened only when
    SQLITE_IMPORT is on and the schema is public.
    """
    conn = get_connection()
    try:
        _create_tables(conn)
    finally:
        conn.close()
    logger.info("PostgreSQL application tables verified.")


def _create_tables(conn):
    conn.execute("""
        CREATE TABLE IF NOT EXISTS accounts (
            id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email           TEXT NOT NULL UNIQUE,
            password_hash   TEXT,
            auth_provider   TEXT NOT NULL DEFAULT 'local',
            session_version INTEGER NOT NULL DEFAULT 1,
            created_at      TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            age              INTEGER NOT NULL,
            income           DOUBLE PRECISION NOT NULL,
            expenses         DOUBLE PRECISION NOT NULL,
            savings          DOUBLE PRECISION NOT NULL,
            risk_appetite    TEXT NOT NULL,
            financial_goals  TEXT NOT NULL,
            account_id       BIGINT REFERENCES accounts(id),
            created_at       TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS reports (
            id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id      BIGINT NOT NULL UNIQUE
                             REFERENCES users(id) ON DELETE CASCADE,
            health_json  JSONB NOT NULL,
            ai_report    TEXT NOT NULL,
            pdf_path     TEXT,
            generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS chat_history (
            id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id    BIGINT NOT NULL
                           REFERENCES users(id) ON DELETE CASCADE,
            role       TEXT NOT NULL CHECK (role IN ('user', 'ai')),
            message    TEXT NOT NULL,
            created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_reports_user_id
        ON reports(user_id)
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_chat_history_user_id
        ON chat_history(user_id, id DESC)
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_users_account_id
        ON users(account_id)
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS jobs (
            id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind          TEXT NOT NULL CHECK (kind IN ('report', 'chat')),
            account_id    BIGINT REFERENCES accounts(id),
            user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            status        TEXT NOT NULL CHECK (status IN ('queued', 'running', 'succeeded', 'failed')),
            payload       TEXT,
            error_code    TEXT,
            error_detail  TEXT,
            attempts      INTEGER NOT NULL DEFAULT 0,
            started_at    TIMESTAMPTZ,
            finished_at   TIMESTAMPTZ,
            created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS idx_jobs_one_active_report
        ON jobs (user_id)
        WHERE kind = 'report' AND status IN ('queued', 'running')
    """)
    conn.execute("ALTER TABLE jobs ADD COLUMN IF NOT EXISTS payload TEXT")
    _allow_chat_jobs(conn)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS api_credentials (
            id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            account_id   BIGINT NOT NULL REFERENCES accounts(id),
            label        TEXT NOT NULL,
            key_hash     TEXT NOT NULL,
            key_sha256   TEXT,
            scopes       TEXT NOT NULL,
            revoked_at   TIMESTAMPTZ,
            created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE INDEX IF NOT EXISTS idx_api_credentials_account
        ON api_credentials (account_id)
    """)
    conn.execute("ALTER TABLE api_credentials ADD COLUMN IF NOT EXISTS key_sha256 TEXT")
    conn.execute("""
        CREATE UNIQUE INDEX IF NOT EXISTS idx_api_credentials_live_key_sha256
        ON api_credentials (key_sha256)
        WHERE revoked_at IS NULL
    """)
    _apply_sql_script(conn, "sessions.sql")
    _apply_sql_script(conn, "auth_challenges.sql")
    pending = conn.execute(
        """
        SELECT COUNT(*) AS n FROM api_credentials
        WHERE revoked_at IS NULL AND key_sha256 IS NULL
        """
    ).fetchone()["n"]
    if pending:
        logger.warning(
            "%s live API credential(s) have no key digest; reissue them with scripts/issue_api_credential.py",
            pending,
        )

    from config import Config
    from database.repository import attach_orphan_profiles

    conn.commit()
    if schema_name() == "public" and Config.SQLITE_IMPORT:
        import_sqlite_if_empty(conn)
    attach_orphan_profiles(conn)
    export_legacy_blobs(conn)
    _drop_pdf_blob_if_clear(conn)
    conn.commit()


def _sql_statements(body: str) -> list[str]:
    """Split on semicolons that are outside dollar-quoted blocks."""
    statements = []
    buf: list[str] = []
    in_dollar = False
    i = 0
    while i < len(body):
        if body.startswith("$$", i):
            in_dollar = not in_dollar
            buf.append("$$")
            i += 2
            continue
        if body[i] == ";" and not in_dollar:
            sql = "".join(buf).strip()
            if sql:
                statements.append(sql)
            buf = []
            i += 1
            continue
        buf.append(body[i])
        i += 1
    tail = "".join(buf).strip()
    if tail:
        statements.append(tail)
    return statements


def _apply_sql_script(conn, filename: str) -> None:
    """Run an idempotent script from database/sql. One statement per execute."""
    path = Path(__file__).resolve().parent / "sql" / filename
    kept = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("--"):
            continue
        kept.append(line)
    for statement in _sql_statements("\n".join(kept)):
        conn.execute(statement)


def _drop_pdf_blob_if_clear(conn):
    """Drop reports.pdf_blob once no row still keeps bytes without a file path."""
    present = conn.execute(
        """
        SELECT 1 AS present
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'reports'
          AND column_name = 'pdf_blob'
        """
    ).fetchone()
    if not present:
        return
    leftover = conn.execute(
        """
        SELECT COUNT(*) AS n FROM reports
        WHERE pdf_blob IS NOT NULL AND length(pdf_blob) > 0
          AND (pdf_path IS NULL OR pdf_path = '')
        """
    ).fetchone()["n"]
    if leftover:
        logger.error(
            "reports.pdf_blob still holds %s file(s) with no path; column kept",
            leftover,
        )
        return
    conn.execute("ALTER TABLE reports DROP COLUMN pdf_blob")
